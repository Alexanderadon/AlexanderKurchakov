// Первый кадр заставки — чистые HTML и CSS, без единой строки JavaScript.
//
// Зачем это отдельно от Preloader.tsx, хотя рисуют они одно и то же.
//
//  1. КОГДА. WebGL-заставка приходит из React и поднимается на 545-780 мс: до
//     гидратации её разметки в документе нет вообще, а `html[data-preload]`
//     уже держит содержимое сайта под visibility:hidden. Полсекунды человек
//     смотрит в пустой прямоугольник цвета фона. Эта оболочка пре-рендерится
//     вместе со страницей и попадает в отдаваемый index.html, поэтому её видно
//     в первом же кадре парсера — примерно за 100 мс, вместе с CSS.
//
//  2. ЧЕМ. WebGL-сцена рисуется в requestAnimationFrame, то есть НА ГЛАВНОМ
//     ПОТОКЕ. Любая длинная задача морозит её по определению, а их там хватает:
//     под заставкой на первом заходе 18 длинных задач общей длиной 4867 мс,
//     худшая — 968 мс (разбор чанка three.js; к заставке отношения не имеет,
//     но поток занимает целиком). Ровно это человек и описывает словами
//     «заставка замирает, мышь застывает». Слой .preboot-pulse анимируется
//     ТОЛЬКО transform и opacity — такая анимация живёт на потоке композитора
//     и продолжает идти, пока главный стоит колом. Он лежит ПОВЕРХ WebGL-холста
//     (z-index 10000 против 9999), иначе его не было бы видно: холст заводится
//     с alpha:false и непрозрачен.
//
//  3. НЕЗАВИСИМОСТЬ. Здесь нет ни состояния, ни эффектов, ни обращений к DOM.
//     Оболочка живёт, даже если сцена не собралась, бандл не приехал или JS
//     отвалился на полпути. Показ и снятие целиком на CSS: видна только под
//     `html[data-preload]`, а этот атрибут ставит инлайновый BOOT-скрипт и
//     снимает либо Preloader.finish(), либо его же предохранитель. Никакой
//     новой логики готовности — Readiness, progressTarget и HARD_BAIL_MS не
//     знают об этом файле ничего.
//
// Доступность: оба слоя aria-hidden. Семантику прогресса (role="progressbar"
// с живым aria-valuenow) отдаёт WebGL-оверлей, и второй такой же ролью на
// экране была бы каша из двух индикаторов.
export function PreloadShell() {
  return (
    <>
      {/* Подложка: непрозрачный фон и латынь. Лежит ПОД WebGL-холстом, поэтому
          после подъёма сцены её просто не видно — снимать нечем и незачем.
          Текст повторяет .preload-top пиксель в пиксель (те же правила в CSS),
          так что подмена одного другим глазом не читается. */}
      <div className="preboot" aria-hidden="true">
        <div className="preboot-glow" />
        <p className="preboot-top">
          LUX IN TENEBRIS LUCET
          <s>и свет во тьме светит</s>
        </p>
      </div>
      {/* Живой слой: поверх всего, полупрозрачный, только transform и opacity. */}
      <div className="preboot-pulse" aria-hidden="true">
        <div className="preboot-vig" />
        <div className="preboot-scan">
          <b />
        </div>
      </div>
    </>
  );
}
