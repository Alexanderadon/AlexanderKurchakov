// Прогиб страницы в жёлоб.
//
// Открытая книга не состоит из двух плоских листов: у корешка страница ныряет
// вниз, а к внешнему обрезу выравнивается. Именно этот прогиб с мягкой тенью в
// жёлобе и читается как «разворот», а без него две страницы выглядят отдельными
// плитами, положенными рядом.
//
// Почему отдельно от изгиба листа. У переворачиваемого листа кривизна РАСТЁТ от
// петли к свободному краю — его поднимают за угол. У лежащей страницы всё
// наоборот: круче всего у корешка, и дальше плоско. Это разные формы, и попытка
// описать их одной формулой давала либо жестяную дугу, либо лист, задранный не
// тем концом.
//
// Отсчёт идёт ОТ УРОВНЯ СТОПКИ, а не вниз от него: z = depth·(1 - exp(-k·s)).
// У корешка страница лежит ровно на стопке, а к внешнему обрезу поднимается —
// получается та самая долина в жёлобе. Считать вниз нельзя: блок у нас плоская
// коробка, долины под ним нет, и страница просто утопала внутрь стопки, оставаясь
// видимой лишь с трёх четвертей ширины.
//
// Показательный спад даёт бесконечно гладкий переход в плоскость, поэтому шва
// между поднятой и плоской частью не видно.

import { MeshStandardMaterial, type IUniform, type Texture, Vector2 } from "three";

/**
 * Крутизна спада жёлоба. При 5.2 прогиб заканчивается примерно на трети ширины
 * страницы — так и лежит бумага в толстом томе.
 *
 * Константа ОДНА на страницу, переворачиваемый лист и веер блока (threeBook):
 * все три поверхности обязаны сходиться в жёлобе, а при трёх копиях числа они
 * уже расходились — лист нырял под страницу, страница под стопку.
 */
export const DIP_K = 5.2;

export interface DipMaterial {
  material: MeshStandardMaterial;
  /** Глубина падения у самого корешка, в единицах сцены. */
  dip: IUniform<number>;
  /**
   * Амплитуда ряби старой бумаги. У корешка листы прижаты швейкой — рябь
   * гаснет тем же спадом, что и жёлоб, и растёт к свободному обрезу.
   */
  ripple: IUniform<number>;
}

/**
 * Материал страницы с прогибом в жёлоб.
 *
 * side: +1 — страница уходит вправо от корешка, -1 — влево. Зеркалить поворотом
 * нельзя: у плоскости повёрнутой на 180° к зрителю оказывается изнанка, которой
 * нет, и страница пропадает — на эти грабли я уже наступил.
 */
export function pageMaterial(
  map: Texture,
  normalMap: Texture,
  side: 1 | -1,
): DipMaterial {
  const dip: IUniform<number> = { value: 0 };
  const ripple: IUniform<number> = { value: 0 };
  const material = new MeshStandardMaterial({
    map,
    normalMap,
    normalScale: new Vector2(0.7, 0.7),
    roughness: 0.95,
    metalness: 0,
    alphaTest: 0.5,
  });
  material.alphaToCoverage = true;
  // Ключ кэша программ. Three собирает его из ПАРАМЕТРОВ материала и ничего не
  // знает о правках из onBeforeCompile. Обе страницы заводятся с одинаковыми
  // параметрами, поэтому вторая молча брала программу первой — левая страница
  // исполняла шейдер правой и ныряла не тем концом: у корешка задиралась, у
  // обреза тонула в стопке, и внешняя треть разворота оставалась залита верхом
  // блока. Без этой строки любые две одинаково настроенные страницы снова
  // склеятся.
  material.customProgramCacheKey = () => `dip${side}`;

  const K = DIP_K;
  const HALF = 0.5; // половина ширины страницы в единицах геометрии
  const s = side > 0 ? `(position.x + ${HALF.toFixed(2)})` : `(${HALF.toFixed(2)} - position.x)`;

  // Фазы ряби у левой и правой страниц разные: одинаковая волна на развороте
  // читалась бы штампованной.
  const p1 = side > 0 ? "0.9" : "2.3";
  const p2 = side > 0 ? "1.7" : "0.4";

  material.onBeforeCompile = (shader) => {
    shader.uniforms.uDip = dip;
    shader.uniforms.uRipple = ripple;
    shader.vertexShader = shader.vertexShader
      .replace("#include <common>", "#include <common>\nuniform float uDip;\nuniform float uRipple;")
      .replace(
        "#include <beginnormal_vertex>",
        `#include <beginnormal_vertex>
    {
      // Наклон поверхности — производные спада и ряби. Без правки нормалей
      // рельеф был бы виден только по силуэту, а свет ложился бы как на плоскость.
      // Вклад ряби ПРИГЛУШЁН (×0.4): полная производная ловила зеркальный лоб
      // солнца, и антиузлы решётки светились ровными овалами.
      float d = uDip > 0.0001 ? uDip * ${K.toFixed(1)} * exp(-${s} * ${K.toFixed(1)}) : 0.0;
      float rEdge = 1.0 - exp(-${s} * ${K.toFixed(1)});
      float dwx = 17.0 * cos(position.x * 17.0 + ${p1}) * sin(position.y * 9.0 + ${p2})
        + 18.6 * cos(position.x * 31.0 + ${p2}) * sin(position.y * 17.0 + ${p1});
      float dwy = 9.0 * sin(position.x * 17.0 + ${p1}) * cos(position.y * 9.0 + ${p2})
        + 10.2 * sin(position.x * 31.0 + ${p2}) * cos(position.y * 17.0 + ${p1});
      float rx = uRipple * rEdge * dwx * 0.3;
      float ry = uRipple * rEdge * dwy * 0.3;
      objectNormal = normalize(vec3(${side > 0 ? "-d" : "d"} - rx, -ry, 1.0));
    }`,
      )
      .replace(
        "#include <begin_vertex>",
        `#include <begin_vertex>
    if (uDip > 0.0001) {
      transformed.z += uDip * (1.0 - exp(-${s} * ${K.toFixed(1)}));
    }
    if (uRipple > 0.0001) {
      // Рябь старой бумаги: гаснет у прижатого швейкой корешка, растёт к обрезу.
      // ДВЕ несоизмеримые октавы: одна решётка sin·sin давала правильную сетку
      // пузырей — бумага так не коробится. Волна смещена В ПЛЮС: бумага коробится
      // ВВЕРХ от стопки; с нулевым средним страница ныряла ниже своего зазора, и
      // сквозь неё резкими пятнами проступал плоский верх веера.
      float rE = 1.0 - exp(-${s} * ${K.toFixed(1)});
      float w = sin(position.x * 17.0 + ${p1}) * sin(position.y * 9.0 + ${p2})
        + 0.6 * sin(position.x * 31.0 + ${p2}) * sin(position.y * 17.0 + ${p1});
      transformed.z += uRipple * rE * (w * 0.5 + 1.0);
    }`,
      );
  };

  return { material, dip, ripple };
}
