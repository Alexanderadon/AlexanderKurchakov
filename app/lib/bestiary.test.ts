// Числа бестиария, от которых зависит и сцена, и её React-обёртка.
//
// Прежние тесты меряли ассеты СТАРОЙ сцены — той, что собиралась из плоских
// картинок и подменяла крышку разворотом в момент, когда элемент повёрнут ребром.
// Сцена давно на three.js и считает геометрию сама, поэтому те замеры убраны
// вместе с константами: два источника правды рядом неизбежно расходятся, и один
// из них начинает тихо врать. Этот тест как раз и поймал расхождение, когда
// страница перешла на готическую пропорцию.

import { describe, expect, it } from "vitest";
import { LEAVES, OPEN_MS, SPREAD_RATIO, TURN_MS } from "./bestiary";

describe("числа бестиария", () => {
  it("пропорция сцены совпадает с геометрией раскрытой книги", () => {
    // Ширина разворота: две крышки по (PAGE_W + кант) плюс два рубчика.
    // Высота: крышка, то есть страница плюс кант сверху и снизу.
    const PAGE_W = 1;
    const PAGE_H = PAGE_W * 1.4459;
    const SQUARE = 0.028;
    const COVER_T = 0.022;
    const width = 2 * (PAGE_W + SQUARE) + 2 * COVER_T;
    const height = PAGE_H + SQUARE * 2;
    expect(SPREAD_RATIO).toBeCloseTo(width / height, 2);
  });

  it("холст не шире самой книги — иначе она болтается в пустоте", () => {
    // Прежние 1586/992 = 1.5988 достались от разворота, нарисованного под
    // квадратную страницу 1:1.25. После перехода на готическую 1:1.446 холст
    // оказался бы шире книги на 14 %.
    expect(SPREAD_RATIO).toBeLessThan(1.45);
    expect(SPREAD_RATIO).toBeGreaterThan(1.3);
  });

  it("такт открытия не превращается в хлопок", () => {
    // 620 мс читались именно хлопком: книга тяжёлая, и спешка выдаёт подделку
    // вернее любой геометрии.
    expect(OPEN_MS).toBeGreaterThanOrEqual(1200);
    expect(OPEN_MS).toBeLessThan(2400);
    expect(TURN_MS).toBeGreaterThan(500);
    expect(TURN_MS).toBeLessThan(OPEN_MS);
  });

  it("листов хватает на разворот с обеих сторон", () => {
    // Книга раскрывается на середине, поэтому листов нужно чётное число и хотя
    // бы по паре на сторону.
    expect(LEAVES % 2).toBe(0);
    expect(LEAVES).toBeGreaterThanOrEqual(4);
  });
});
