// Скрипт, который обязан отработать ДО первой отрисовки: восстановить палитру,
// шрифты и язык из localStorage и решить, показывать ли прелоадер. Сделать это
// в React нельзя — он отработает уже после гидратации, и страница успеет мигнуть
// и контентом, и не той палитрой.
//
// Но писать его строкой тоже незачем: функция ниже — обычный TypeScript, её
// проверяет tsc и видит IDE, а в разметку она попадает через toString().
//
// Единственное требование: функция должна быть САМОДОСТАТОЧНОЙ. Любая ссылка на
// внешний идентификатор после сборки превратится в имя, которого в инлайновом
// скрипте не существует. За этим следит тест.

import { BOOT_GATE_MS } from "./preloadTiming";

type Conn = { saveData?: boolean };

function boot(d: HTMLElement, gateMs: number): void {
  d.classList.add("js");
  try {
    const p = localStorage.getItem("bento2:palette");
    if (p === "graphite" || p === "midnight") d.setAttribute("data-palette", p);
    const f = localStorage.getItem("bento2:fonts");
    if (f === "strict") d.setAttribute("data-fonts", f);
    const l = localStorage.getItem("bento2:lang");
    if (l === "kz") d.lang = "kk";
    else if (l === "en") d.lang = "en";
  } catch {
    /* приватный режим */
  }
  try {
    // Заставка показывается НА КАЖДОЙ загрузке документа, включая перезагрузку.
    //
    // Раньше она шла раз за сессию. Причина отказаться конкретная и измеримая:
    // скомпилированные шейдерные программы браузер между загрузками не хранит
    // вообще, поэтому каждая загрузка заново платит линковку — на прод-сборке
    // это 550–771 мс длинных задач. Под заставкой их не видно, без неё они
    // бьют по уже показанной странице, и это ровно те «фризы при обновлении»,
    // на которые жалуются. Прятать эту работу — единственный способ, убрать её
    // нельзя.
    //
    // Возврат по bfcache (кнопка «назад») сюда не попадает: документ не
    // разбирается заново, и инлайновый скрипт не исполняется.
    const c = (navigator as Navigator & { connection?: Conn }).connection;
    const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (!reduced && !(c && c.saveData)) {
      d.setAttribute("data-preload", "");
      setTimeout(function () {
        d.removeAttribute("data-preload");
      }, gateMs);
    }
  } catch {
    /* приватный режим */
  }
}

/**
 * Готовая к вставке в <script> строка.
 *
 * Время предохранителя передаётся АРГУМЕНТОМ, а не стоит числом внутри функции:
 * оно связано инвариантом с пределом жизни оверлея, а сослаться на импорт по
 * имени нельзя — после toString() в инлайновом скрипте такого идентификатора не
 * существует. Раньше числа стояли в двух файлах и разъехались: предохранитель
 * снимал гейт на восьмой секунде, а компонент уходил на двадцатой.
 */
export const BOOT_SCRIPT = `(${boot.toString()})(document.documentElement, ${BOOT_GATE_MS})`;
