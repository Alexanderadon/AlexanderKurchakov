// Геометрия бестиария — снята замером с самих картинок, а не подобрана на глаз.
// Пергамент отделён от переплёта по яркости (порог 0.45), границы взяты по
// строке через середину разворота. Пересчитывать при замене ассетов.

/** Разворот: 1586×992 в исходнике. */
export const SPREAD_RATIO = 1586 / 992;
/** Закрытая обложка: 1448×1086. */
export const COVER_RATIO = 1448 / 1086;

/**
 * Область правой страницы в долях разворота. Ось переворота — жёлоб; он лёг
 * ровно по центру (50.06%), но константу держим из замера, а не как 0.5:
 * при перегенерации разворота центр уедет, и лучше это увидеть в тесте.
 */
export const PAGE = {
  gutter: 794 / 1586,
  right: 1421 / 1586,
  top: 27 / 992,
  bottom: 953 / 992,
} as const;

export const pageWidth = (): number => PAGE.right - PAGE.gutter;
export const pageHeight = (): number => PAGE.bottom - PAGE.top;

/**
 * Пропорция переворачиваемого листа (ш/в) — считается ОТ ЖЁЛОБА, а не от края
 * видимого пергамента. Разница существенная: пергамент начинается на x=832
 * (ширина 588 px), но лист вращается вокруг жёлоба на x=794, то есть занимает
 * 627 px. Отсюда 0.677, а не 0.635; присланный отдельный лист даёт 0.667 и
 * сходится с этим в пределах полутора процентов — подрезать почти нечего.
 */
export const pageAspectInSpread = (): number =>
  (pageWidth() * SPREAD_RATIO) / pageHeight();

/**
 * Обложка шире половины разворота — книга сгенерирована альбомной, а страницы
 * книжные. Отсюда единственно возможная механика открытия: подмена в момент,
 * когда элемент повёрнут ребром к зрителю и его ширина равна нулю.
 */
export const coverOverhang = (): number => COVER_RATIO / (SPREAD_RATIO / 2);

/** Такт открытия, мс. Половина — уход обложки, половина — приход разворота. */
export const OPEN_MS = 620;
/** Переворот страницы, мс. */
export const TURN_MS = 700;
