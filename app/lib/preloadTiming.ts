// Тайминги заставки. ОДИН модуль на всех, потому что между ними есть инвариант,
// а лежали они в разных файлах и разъехались.
//
// Как было. В инлайновом скрипте (boot.ts) стоял предохранитель на 8000 мс: он
// снимает атрибут data-preload, если React почему-то не поднялся, — иначе сайт
// остался бы невидимым навсегда. В самом компоненте стоял свой жёсткий предел,
// сперва 6500 мс, и порядок держался сам собой: компонент уходил раньше, а
// предохранитель был мёртвой страховкой.
//
// Потом предел компонента подняли до 20000 мс — чтобы дождаться книги. Порядок
// перевернулся, и появилось окно: атрибут снят на восьмой секунде, содержимое
// страницы уже показано и доступно табу, а сверху ещё лежит НЕПРОЗРАЧНЫЙ оверлей
// (canvas заводится с alpha:false), у которого pointer-events:none появляется
// только на фазе затухания. Четырнадцать секунд страница ловила клики в пустоту.
//
// Инвариант простой: предохранитель обязан быть ПОЗЖЕ, чем компонент уходит сам
// со всеми своими фазами. За этим следит тест.

/**
 * Жёсткий предел жизни оверлея. Считать завершение только по кадрам нельзя: во
 * вкладке, открытой в фоне, requestAnimationFrame не вызывается вообще, и
 * прелоадер досчитывал бы вечно. Таймер работает независимо от кадров.
 *
 * Это ПАТОЛОГИЯ (мёртвый WebGL, битые ассеты), а не нормальный путь: обычно
 * оверлей уходит по готовности, включая готовность книги. Замер прод-сборки:
 * 3.5–4.5 с от загрузки до ухода.
 */
export const HARD_BAIL_MS = 9000;

/** Плавное исчезновение оверлея, мс. Должно совпасть с transition в CSS. */
export const FADE_MS = 600;

/** Разлив света в конце, мс. */
export const FINALE_MS = 900;

/**
 * Предохранитель в инлайновом скрипте: через сколько снять data-preload, если
 * компонент так и не заявил о себе. Запас поверх полного цикла оверлея — на
 * случай медленной гидратации: у двух таймеров РАЗНЫЕ нули (этот считается от
 * разбора <head>, предел компонента — от его второго эффекта), и зазор между
 * ними растёт ровно на время загрузки и гидратации.
 */
export const BOOT_GATE_MS = HARD_BAIL_MS + FADE_MS + 3500;
