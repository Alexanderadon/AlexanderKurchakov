// Бюджеты сцены. Это не тест поведения — это ловушка на регрессию по цене.
//
// Зачем отдельно. Всё, что стоило этому проекту недели разбора, проходило и типы,
// и модульные тесты, и e2e:
//   • 400 000 треугольников ради смещения глубиной в 0.75% ширины страницы;
//   • 37 шейдерных программ на один предмет вместо необходимых;
//   • переключение теней, пересобиравшее весь набор программ дважды за одно
//     открытие книги.
// Ни одну из этих вещей нельзя увидеть глазом или в код-ревью. Они видны только
// счётчиком.
//
// Почему меряем ЧИСЛО ПРОГРАММ, а не время. Время на CI бессмысленно: там нет
// видеокарты, WebGL идёт через программный растеризатор, и любая секунда там
// значит не то же самое, что на живой машине. А число программ от железа НЕ
// ЗАВИСИТ вовсе — оно определяется тем, сколько разных наборов слотов у
// материалов сцены. Тот же счёт на любом раннере, без флаки.
//
// Цена одной программы на живой машине — около 78 мс ожидания драйвера. То есть
// каждая лишняя программа это примерно десятая доля секунды в заставке, которую
// пользователь пересиживает при КАЖДОЙ загрузке.
import { expect, test } from "@playwright/test";

/**
 * Потолок числа программ во всех WebGL-контекстах страницы.
 *
 * На момент установки: 29 (27 книга + туман + заставка). Запас три штуки — на
 * осмысленную новую поверхность, а не на копипасту материала. Если тест упал:
 * посмотрите, не завёлся ли материал, отличающийся от соседнего только НАБОРОМ
 * КАРТ — такие сливаются заглушкой 1x1 (белый пиксель для карты цвета, плоская
 * нормаль для рельефа), и кадр от этого не меняется. Разбор такого слияния
 * лежит в комментариях к материалам в threeBook.ts.
 *
 * Поднимать это число можно — но осознанно и вместе с объяснением в коммите,
 * а не «чтобы CI позеленел».
 */
const MAX_PROGRAMS = 32;

test("бюджет: число шейдерных программ", async ({ page }) => {
  test.slow(); // книга собирается под заставкой, это не быстро даже на CI

  await page.addInitScript(() => {
    const w = window as unknown as { __progs: number };
    w.__progs = 0;
    for (const proto of [
      WebGLRenderingContext.prototype,
      typeof WebGL2RenderingContext !== "undefined" ? WebGL2RenderingContext.prototype : null,
    ]) {
      if (!proto) continue;
      const orig = proto.createProgram;
      proto.createProgram = function (this: WebGLRenderingContext) {
        w.__progs++;
        return orig.call(this);
      };
    }
  });

  await page.goto("/");
  // Книга собирается под заставкой и сигналит готовность — ждём её ухода,
  // иначе посчитаем половину программ и тест будет зелёным вхолостую.
  await expect(page.locator(".preload")).toHaveCount(0, { timeout: 40_000 });
  await page.waitForTimeout(1500);

  const progs = await page.evaluate(() => (window as unknown as { __progs: number }).__progs);
  // Ноль означает, что WebGL на раннере не поднялся вовсе: тогда бюджет нечего
  // проверять, и молчаливый зелёный тут хуже пропуска.
  test.skip(progs === 0, "WebGL на этом раннере недоступен — бюджет не проверить");
  expect(progs, `шейдерных программ ${progs}, потолок ${MAX_PROGRAMS}`).toBeLessThanOrEqual(
    MAX_PROGRAMS,
  );
});
